#!/usr/bin/env python3
"""
Sibling-project isolation — one focused product, opaque neighbors.

The IDE workspace is the studio root, so agents can otherwise Read/Grep/git
every tree under projects/. Focus writes a Cursor ignore list and a local
rule so only projects/<active>/ is in the working set.
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path
from typing import List, Optional, Tuple

STUDIO_ROOT = Path(__file__).parent.parent.parent
QUINSY_STUDIO = STUDIO_ROOT / ".quinsy-studio"
PROJECTS_DIR = STUDIO_ROOT / "projects"

ISOLATION_BEGIN = "# BEGIN QUINSY-ISOLATION"
ISOLATION_END = "# END QUINSY-ISOLATION"
SECRETS_BEGIN = "# BEGIN QUINSY-SECRETS"
SECRETS_END = "# END QUINSY-SECRETS"
CURSORIGNORE_PATH = STUDIO_ROOT / ".cursorignore"
ISOLATION_RULE_PATH = STUDIO_ROOT / ".cursor" / "rules" / "quinsy-project-isolation.mdc"
HOOK_MARKER = "QUINSY-ISOLATION"
HQ_HOOK_MARKER = "QUINSY-HQ-HOOK"
ENV_SCHEMA_PATH = QUINSY_STUDIO / "studio-templates" / "env.schema.json"

_CLI_JUNK_PROJECT_RE = re.compile(r"^(LO-\d+|testproj)$")


def _looks_like_real_project(child: Path) -> bool:
    name = child.name
    if name.startswith("-") or name.startswith("."):
        return False
    if _CLI_JUNK_PROJECT_RE.match(name):
        return False
    return (child / "status.json").exists() or (child / ".git").exists()


def list_real_projects() -> List[str]:
    if not PROJECTS_DIR.is_dir():
        return []
    names: List[str] = []
    for child in sorted(PROJECTS_DIR.iterdir()):
        if child.is_dir() and _looks_like_real_project(child):
            names.append(child.name)
    return names


def sibling_projects(project: str) -> List[str]:
    return [n for n in list_real_projects() if n != project]


def request_names_sibling(request: str, project: str) -> Optional[str]:
    """Return a sibling folder name mentioned in the user request, if any."""
    blob = (request or "").lower()
    if not blob:
        return None
    for sib in sibling_projects(project):
        key = sib.lower()
        if f"projects/{key}" in blob.replace("\\", "/"):
            return sib
        if re.search(rf"(?<![a-z0-9-]){re.escape(key)}(?![a-z0-9-])", blob):
            return sib
    return None


def path_escapes_project(project: str, rel_or_abs: str) -> bool:
    """True if a filesystem path is under a different projects/<name>/ tree."""
    raw = (rel_or_abs or "").strip()
    if not raw:
        return False
    path = Path(raw)
    if not path.is_absolute():
        path = (STUDIO_ROOT / path).resolve()
    else:
        path = path.resolve()
    try:
        rel = path.relative_to(PROJECTS_DIR.resolve())
    except ValueError:
        return False
    parts = rel.parts
    if not parts:
        return False
    return parts[0] != project


def _strip_marked_block(text: str, begin: str, end: str) -> str:
    if begin not in text:
        return text.rstrip() + ("\n" if text and not text.endswith("\n") else "")
    before, rest = text.split(begin, 1)
    if end in rest:
        _, after = rest.split(end, 1)
    else:
        after = ""
    return (before.rstrip() + "\n" + after.lstrip("\n")).lstrip("\n")


def _cursorignore_without_block(text: str) -> str:
    """Drop isolation and secrets blocks; keep any manual lines."""
    out = _strip_marked_block(text, ISOLATION_BEGIN, ISOLATION_END)
    return _strip_marked_block(out, SECRETS_BEGIN, SECRETS_END)


def secrets_ignore_block() -> str:
    """Cursor deny list for env *values* — including the focused product."""
    lines = [
        SECRETS_BEGIN,
        "# LO-0314 — secret values are not agent-readable (focused project included).",
        "# Names live in .quinsy-studio/studio-templates/env.schema.json and *.env.example.",
        "**/.env",
        "**/.env.local",
        "**/.env.*.local",
        "!**/.env.example",
        "**/*.pem",
        "**/*.key",
        ".quinsy-studio/.secrets/",
        ".quinsy-studio/.secrets/**",
        "projects/*/.env",
        "projects/*/.env.local",
        SECRETS_END,
    ]
    return "\n".join(lines) + "\n"


def host_secret_dir(project: str) -> Path:
    """Host-side values dir — outside the git workspace when possible."""
    import sys

    slug = (project or "studio").strip() or "studio"
    if sys.platform == "darwin":
        return (
            Path.home()
            / "Library"
            / "Application Support"
            / "quinsy-studio"
            / "secrets"
            / slug
        )
    return Path.home() / ".config" / "quinsy-studio" / "secrets" / slug


def _isolation_block(siblings: List[str]) -> str:
    lines = [ISOLATION_BEGIN, "# Regenerated by ./studio focus — sibling project trees are opaque."]
    if not siblings:
        lines.append("# (no sibling projects)")
    for name in siblings:
        lines.append(f"projects/{name}/")
        lines.append(f"projects/{name}/**")
    lines.append(ISOLATION_END)
    return "\n".join(lines) + "\n"


def write_cursorignore(siblings: List[str]) -> Path:
    existing = ""
    if CURSORIGNORE_PATH.exists():
        existing = CURSORIGNORE_PATH.read_text(encoding="utf-8")
    kept = _cursorignore_without_block(existing).rstrip()
    parts = []
    if kept:
        parts.append(kept)
    parts.append(secrets_ignore_block().rstrip())
    parts.append(_isolation_block(siblings).rstrip())
    CURSORIGNORE_PATH.write_text("\n\n".join(parts) + "\n", encoding="utf-8")
    return CURSORIGNORE_PATH


def write_isolation_rule(project: str, siblings: List[str]) -> Path:
    sib = ", ".join(f"`projects/{n}/`" for n in siblings) or "(none)"
    text = f"""---
description: Quinsy Studio — sibling project isolation (generated by ./studio focus)
alwaysApply: true
---

# Project isolation (generated)

Active product: **`projects/{project}/`** only.

Sibling trees are **out of bounds**: {sib}

- Do **not** Read, Grep, Glob, Shell-`ls`, or open files under those folders.
- Do **not** copy, merge, submodule, or `git add` another project's source into this git repo.
- Do **not** `git remote add` / fetch / push a sibling product remote into this repo.
- Project git runs **inside** `projects/{project}/` (`git -C projects/{project} …`). Toplevel must be that folder — never the studio root, never a sibling.
- Studio HQ (`.quinsy-studio/`) is allowed for LO/process/tooling. Product code is only `projects/{project}/`.
- **Secrets:** do **not** Read, Grep, or Shell-print `.env` / `.env.local` / `*.pem` **values** (this project included). Use `env.schema.json` / `.env.example` for **names**. Inject values only via `./studio env … --approve` (LO-0315).
- Switching products: `./studio focus <other>` (rewrites this gate). Do not keep two product trees in one commit.
"""
    ISOLATION_RULE_PATH.parent.mkdir(parents=True, exist_ok=True)
    ISOLATION_RULE_PATH.write_text(text, encoding="utf-8")
    return ISOLATION_RULE_PATH


def install_project_git_hook(project: str) -> Optional[Path]:
    """Refuse commits whose worktree or staged paths are not this project."""
    expected = str((PROJECTS_DIR / project).resolve()).replace("'", "'\\''")
    git_dir = PROJECTS_DIR / project / ".git"
    if not git_dir.exists():
        return None
    # Worktrees use a gitfile; hooks live in the real git dir.
    if git_dir.is_file():
        raw = git_dir.read_text(encoding="utf-8", errors="ignore")
        match = re.search(r"^gitdir:\s*(.+)$", raw, re.M)
        if not match:
            return None
        git_dir = Path(match.group(1).strip())
        if not git_dir.is_absolute():
            git_dir = (PROJECTS_DIR / project / git_dir).resolve()
    hooks = git_dir / "hooks"
    hooks.mkdir(parents=True, exist_ok=True)
    hook = hooks / "pre-commit"
    # Do not pipe into `while` — that runs in a subshell and `exit 1` would not fail the hook.
    script = f"""#!/bin/sh
# QUINSY-ISOLATION — do not commit another studio project into this repo
expected='{expected}'
toplevel=$(git rev-parse --show-toplevel) || exit 1
if [ "$toplevel" != "$expected" ]; then
  echo "quinsy isolation: git toplevel is $toplevel (expected $expected)" >&2
  exit 1
fi
tmp=$(mktemp) || exit 1
trap 'rm -f "$tmp"' EXIT
git diff --cached --name-only > "$tmp" || exit 1
while IFS= read -r f; do
  [ -n "$f" ] || continue
  case "$f" in
    ../*|*/../*)
      echo "quinsy isolation: staged path escapes the project repo: $f" >&2
      exit 1
      ;;
  esac
  if [ -L "$toplevel/$f" ]; then
    target=$(readlink "$toplevel/$f")
    case "$target" in
      */projects/*)
        echo "quinsy isolation: staged symlink points at another studio project: $f -> $target" >&2
        exit 1
        ;;
    esac
  fi
done < "$tmp"
"""
    if hook.exists():
        prev = hook.read_text(encoding="utf-8", errors="ignore")
        if HOOK_MARKER not in prev:
            return None
    hook.write_text(script, encoding="utf-8")
    hook.chmod(0o755)
    return hook


_LOCAL_ONLY_PREFIXES = (
    "projects/",
    "intake/",
    "ideation/",
    ".quinsy-studio/backlog/",
    ".quinsy-studio/retros/",
    ".quinsy-studio/sprints/",
    ".quinsy-studio/knowledge-base/learnings/archive/",
)


def hq_commit_blocked(staged: List[str]) -> Optional[str]:
    """Studio HQ git keeps the skilled result, not working notes or product trees."""
    for raw in staged:
        norm = str(raw).replace("\\", "/")
        while norm.startswith("./"):
            norm = norm[2:]
        if norm == "projects" or norm.startswith("projects/"):
            return (
                f"quinsy HQ: refuse staging product path {raw}. "
                "Product git lives inside projects/<name>/ — never the studio index."
            )
        if norm == ".quinsy-studio/knowledge-base/learnings/train-queue.json":
            return f"quinsy HQ: refuse staging the train queue {raw}."
        for prefix in _LOCAL_ONLY_PREFIXES:
            if norm == prefix.rstrip("/") or norm.startswith(prefix):
                return f"quinsy HQ: refuse staging local working notes {raw}."
    return None


def studio_hq_pre_commit_script() -> str:
    sample = QUINSY_STUDIO / "studio-templates" / "hooks" / "studio-hq-pre-commit.sh"
    if sample.exists():
        return sample.read_text(encoding="utf-8")
    return """#!/bin/sh
# QUINSY-HQ-HOOK — studio root must not stage projects/
git diff --cached --name-only | while IFS= read -r f; do
  case "$f" in
    projects|projects/*) echo "quinsy HQ: refuse $f" >&2; exit 1 ;;
  esac
done
"""


def install_studio_hq_git_hook(studio_root: Optional[Path] = None) -> Optional[Path]:
    root = studio_root or STUDIO_ROOT
    git_dir = root / ".git"
    if git_dir.is_file():
        raw = git_dir.read_text(encoding="utf-8", errors="ignore")
        match = re.search(r"^gitdir:\s*(.+)$", raw, re.M)
        if not match:
            return None
        git_dir = Path(match.group(1).strip())
        if not git_dir.is_absolute():
            git_dir = (root / git_dir).resolve()
    elif not git_dir.is_dir():
        return None
    hooks = git_dir / "hooks"
    hooks.mkdir(parents=True, exist_ok=True)
    hook = hooks / "pre-commit"
    script = studio_hq_pre_commit_script()
    if hook.exists():
        prev = hook.read_text(encoding="utf-8", errors="ignore")
        if HQ_HOOK_MARKER not in prev and HOOK_MARKER not in prev:
            backup = hook.with_suffix(".pre-quinsy-hq")
            backup.write_text(prev, encoding="utf-8")
    hook.write_text(script, encoding="utf-8")
    hook.chmod(0o755)
    return hook


def apply_project_isolation(project: str) -> Tuple[List[str], Path, Path]:
    """Hide sibling projects from the IDE agent and stamp the focus rule."""
    siblings = sibling_projects(project)
    ignore = write_cursorignore(siblings)
    rule = write_isolation_rule(project, siblings)
    install_project_git_hook(project)
    return siblings, ignore, rule


def cursorignore_hides_secret_values() -> bool:
    if not CURSORIGNORE_PATH.exists():
        return False
    text = CURSORIGNORE_PATH.read_text(encoding="utf-8")
    if SECRETS_BEGIN not in text or "**/.env" not in text:
        return False
    return True


def cursorignore_lists_siblings(project: str) -> bool:
    if not CURSORIGNORE_PATH.exists():
        return not sibling_projects(project)
    text = CURSORIGNORE_PATH.read_text(encoding="utf-8")
    if ISOLATION_BEGIN not in text:
        return not sibling_projects(project)
    for name in sibling_projects(project):
        if f"projects/{name}/" not in text:
            return False
    return True


def project_git_isolation_issues(project: str) -> List[str]:
    """Detect a project git whose toplevel is not this folder (wrong repo)."""
    root = (PROJECTS_DIR / project).resolve()
    if not root.is_dir():
        return []
    git = root / ".git"
    if not git.exists():
        return []
    try:
        proc = subprocess.run(
            ["git", "-C", str(root), "rev-parse", "--show-toplevel"],
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return []
    if proc.returncode != 0:
        return []
    top = Path(proc.stdout.strip()).resolve()
    if top != root:
        return [
            f"Project '{project}' git toplevel is {top} (expected {root}) — "
            "do not commit another repo into this project"
        ]
    return []


def isolation_issues(project: Optional[str] = None) -> List[str]:
    """Stale Cursor ignore or wrong project git toplevel."""
    issues: List[str] = []
    if not project:
        return issues
    if not cursorignore_lists_siblings(project):
        issues.append(
            f"Sibling isolation stale for '{project}' — run ./studio focus {project}"
        )
    if not cursorignore_hides_secret_values():
        issues.append(
            "Cursor ignore missing QUINSY-SECRETS block — run ./studio focus <project> "
            "(LO-0314: .env values must not be agent-readable)"
        )
    issues.extend(project_git_isolation_issues(project))
    return issues
